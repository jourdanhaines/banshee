// Command gen builds the emoji provider's TSV dataset from Unicode's
// emoji-test.txt and CLDR's English annotations.
package main

import (
	"bytes"
	"context"
	"flag"
	"fmt"
	"io"
	"net/http"
	"os"
	"strings"
	"time"
)

const (
	emojiVersion = "18.0"
	cldrTag      = "release-49"
	maxBody      = 8 << 20
)

var (
	emojiTestURL   = "https://www.unicode.org/Public/" + emojiVersion + ".0/emoji/emoji-test.txt"
	annotationsURL = "https://raw.githubusercontent.com/unicode-org/cldr/" + cldrTag + "/common/annotations/en.xml"
	derivedURL     = "https://raw.githubusercontent.com/unicode-org/cldr/" + cldrTag + "/common/annotationsDerived/en.xml"
)

// headerLines is the comment block at the top of the generated file.
func headerLines() []string {
	return []string{
		"Code generated by internal/providers/emoji/gen; DO NOT EDIT.",
		"Source: Unicode Emoji " + emojiVersion + " emoji-test.txt; CLDR " + cldrTag + " annotations/en.xml + annotationsDerived/en.xml",
		"Format: VALUE<TAB>LABEL<TAB>kw1|kw2|… per base; <TAB>VALUE<TAB>LABEL is a skin-tone variant of the base above.",
	}
}

func main() {
	out := flag.String("out", "emoji.tsv", "output TSV path")
	emojiTest := flag.String("emoji-test", emojiTestURL, "emoji-test.txt URL or local path")
	annotations := flag.String("annotations", annotationsURL, "CLDR annotations/en.xml URL or local path")
	derived := flag.String("derived", derivedURL, "CLDR annotationsDerived/en.xml URL or local path")
	flag.Parse()
	if err := run(context.Background(), *out, *emojiTest, *annotations, *derived); err != nil {
		fmt.Fprintln(os.Stderr, "emoji gen:", err)
		os.Exit(1)
	}
}

func run(ctx context.Context, out, emojiTest, annotations, derived string) error {
	raw, err := fetch(ctx, emojiTest)
	if err != nil {
		return err
	}
	rows, version, err := parseEmojiTest(bytes.NewReader(raw))
	if err != nil {
		return fmt.Errorf("%s: %w", emojiTest, err)
	}
	if version != emojiVersion {
		return fmt.Errorf("%s: version %q, want %q", emojiTest, version, emojiVersion)
	}
	es, err := group(rows)
	if err != nil {
		return err
	}
	var sources []map[string][]string
	for _, src := range []string{annotations, derived} {
		raw, err := fetch(ctx, src)
		if err != nil {
			return err
		}
		m, err := parseAnnotations(bytes.NewReader(raw))
		if err != nil {
			return fmt.Errorf("%s: %w", src, err)
		}
		sources = append(sources, m)
	}
	if err := attachKeywords(es, sources...); err != nil {
		return err
	}
	var buf bytes.Buffer
	if err := write(&buf, es, headerLines()); err != nil {
		return err
	}
	return os.WriteFile(out, buf.Bytes(), 0o644)
}

// fetch reads src over HTTP when it looks like a URL, else from disk.
func fetch(ctx context.Context, src string) ([]byte, error) {
	if !strings.HasPrefix(src, "http") {
		return os.ReadFile(src)
	}
	req, err := http.NewRequestWithContext(ctx, http.MethodGet, src, nil)
	if err != nil {
		return nil, err
	}
	resp, err := (&http.Client{Timeout: 60 * time.Second}).Do(req)
	if err != nil {
		return nil, err
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("%s: %s", src, resp.Status)
	}
	body, err := io.ReadAll(io.LimitReader(resp.Body, maxBody+1))
	if err != nil {
		return nil, fmt.Errorf("%s: %w", src, err)
	}
	if len(body) > maxBody {
		return nil, fmt.Errorf("%s: body exceeds %d bytes", src, maxBody)
	}
	return body, nil
}
